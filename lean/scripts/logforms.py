# Generates lean/Pilean/PiFormula/LogForms.lean: for b in {1, 41, 49, 61, 73, 97} and each of the 13
# relations, the exact value of  sum_j rel_l(b j mod 120) Log w_j  as a rational multiple of
# i pi, and the combined statement for a coefficient vector c.
#
#   python lean/scripts/logforms.py > lean/Pilean/PiFormula/LogForms.lean
#
# The rational multiples are computed here from the table of arguments (argtable.py); Lean
# recomputes each of them (`decide +kernel`), so nothing in this script is trusted.
import sys, io
from fractions import Fraction as Fr

R0 = [0, 60, 30, 90, 20, 100, 15, 45, 75, 105, 12, 36, 84, 108, 10, 50, 18, 42, 66, 114,
      5, 25, 65, 85]
rels = [
    {0: -1, 30: 1},
    {0: -2, 20: 1, 100: 1},
    {0: -2, 15: 1, 75: 1},
    {0: -3, 12: 1, 36: 1, 60: -1, 84: 1, 108: 1},
    {10: 1, 20: -1},
    {0: -2, 20: 1, 50: 1},
    {12: -4, 18: 4, 60: 1, 90: -1},
    {0: -12, 12: 4, 36: 4, 42: 4, 60: -3, 84: 4, 90: -1},
    {60: 1, 66: 4, 84: -4, 90: -1},
    {36: -4, 60: 1, 90: -1, 114: 4},
    {5: -2, 25: 2, 45: 1, 105: -1},
    {0: -2, 5: 2, 45: -1, 65: 2, 105: -1},
    {0: -1, 5: 1, 45: -1, 85: 1},
]
T = {0: (Fr(1, 4), 0, 0), 30: (Fr(-1, 4), 0, 0), 60: (0, 1, 0), 90: (0, -1, 0),
     20: (Fr(-1, 6), 0, 0), 10: (Fr(1, 6), 0, 0), 100: (Fr(1, 6), 0, 0), 50: (Fr(-1, 6), 0, 0),
     15: (0, 0, 0), 75: (0, 0, 0), 45: (Fr(-2, 3), 0, 2), 105: (Fr(2, 3), 0, -2),
     5: (0, 0, 1), 25: (0, 0, -1), 65: (Fr(1, 6), 0, -1), 85: (Fr(-1, 6), 0, 1),
     12: (Fr(11, 80), Fr(1, 4), 0), 18: (Fr(-11, 80), Fr(-1, 4), 0),
     84: (Fr(7, 80), Fr(1, 4), 0), 66: (Fr(-7, 80), Fr(-1, 4), 0),
     108: (Fr(19, 80), Fr(1, 4), 0), 42: (Fr(-19, 80), Fr(-1, 4), 0),
     36: (Fr(-17, 80), Fr(1, 4), 0), 114: (Fr(17, 80), Fr(-1, 4), 0)}
BS = [1, 41, 49, 61, 73, 97]


def nu(b, r):
    A = B = C = Fr(0)
    for j in R0:
        e = r.get(b * j % 120, 0)
        A += e * Fr(T[j][0])
        B += e * Fr(T[j][1])
        C += e * Fr(T[j][2])
    assert B == 0 and C == 0
    return A


def q(x):
    x = Fr(x)
    if x.denominator == 1:
        return str(x.numerator)
    return "%d / %d" % (x.numerator, x.denominator)


out = io.StringIO()
w = out.write
w("""import Pilean.PiFormula.ExactArgs

/-!
# Exact logarithmic forms of the conjugated relations (milestone M7, part 2)

Generated by lean/scripts/logforms.py. For `b ∈ {1, 41, 49, 61, 73, 97}` and each of the 13
relations `rel_l`, the vector `j ↦ rel_l (b j mod 120)` is again a relation (`isRelJ_comp`), and

  `∑_j rel_l (b j mod 120) · Log w_j = ν · iπ`

with an explicit rational `ν` (`lf_b_l`), by `log_exact` and three kernel computations. Summed
against a coefficient vector `c` this gives `conjlog_b`.
-/

open Complex

namespace PiFormula

theorem sum_combC_comp (c : Fin 13 → ℂ) (J : Finset ℕ) (φ : ℕ → ℕ) (L : ℕ → ℂ) :
    ∑ j ∈ J, combC c (φ j) * L j =
      c 0 * ∑ j ∈ J, (rel1 (φ j) : ℂ) * L j + c 1 * ∑ j ∈ J, (rel2 (φ j) : ℂ) * L j
        + c 2 * ∑ j ∈ J, (rel3 (φ j) : ℂ) * L j + c 3 * ∑ j ∈ J, (rel4 (φ j) : ℂ) * L j
        + c 4 * ∑ j ∈ J, (rel5 (φ j) : ℂ) * L j + c 5 * ∑ j ∈ J, (rel6 (φ j) : ℂ) * L j
        + c 6 * ∑ j ∈ J, (rel7 (φ j) : ℂ) * L j + c 7 * ∑ j ∈ J, (rel8 (φ j) : ℂ) * L j
        + c 8 * ∑ j ∈ J, (rel9 (φ j) : ℂ) * L j + c 9 * ∑ j ∈ J, (rel10 (φ j) : ℂ) * L j
        + c 10 * ∑ j ∈ J, (rel11 (φ j) : ℂ) * L j + c 11 * ∑ j ∈ J, (rel12 (φ j) : ℂ) * L j
        + c 12 * ∑ j ∈ J, (rel13 (φ j) : ℂ) * L j := by
  simp only [Finset.mul_sum, ← Finset.sum_add_distrib]
  exact Finset.sum_congr rfl fun j _ => by simp only [combC]; ring

""")

for b in BS:
    a = pow(b, -1, 120)
    w("/-! ## The conjugation `b = %d` (inverse `%d`) -/\n\n" % (b, a))
    w("theorem maps_%d : ∀ j ∈ R0Exps, %d * j %% 120 ∈ R0Exps := by decide\n\n" % (b, b))
    w("theorem inv_%d_%d : ∀ j ∈ R0Exps, %d * (%d * j %% 120) %% 120 = j := by decide\n\n"
      % (a, b, a, b))
    w("theorem off_%d : ∀ x ∈ Finset.range 120, x ∉ R0Exps → %d * x %% 120 ∉ R0Exps := by\n"
      "  decide +kernel\n\n" % (b, b))
for b in BS:
    a = pow(b, -1, 120)
    vals = []
    for l, r in enumerate(rels, 1):
        v = nu(b, r)
        vals.append(v)
        f = "rel%d (%d * j %% 120)" % (l, b)
        w("theorem lf_%d_%d : ∑ j ∈ R0Exps, ((%s : ℤ) : ℂ) * Complex.log (wJ j) =\n"
          "    ((%s : ℚ) : ℂ) * (Real.pi * I) := by\n" % (b, l, f, q(v)))
        w("  have h := log_exact (isRelJ_comp rel%d_isRel (a := %d) (b := %d) (by norm_num)\n"
          "    (by norm_num) maps_%d maps_%d inv_%d_%d inv_%d_%d)\n"
          "    (by decide +kernel) (by decide +kernel)\n" % (l, a, b, b, a, a, b, b, a))
        w("  have hv : (∑ j ∈ R0Exps, ((%s : ℤ) : ℚ) * alpha j) = %s := by\n"
          "    decide +kernel\n" % (f, q(v)))
        w("  rw [hv] at h\n  exact h\n\n")
    terms = ["c %d * (%s)" % (l, q(v)) for l, v in enumerate(vals)]
    rhs = " + ".join(terms[:5]) + "\n      + " + " + ".join(terms[5:9]) + "\n      + " + \
        " + ".join(terms[9:])
    w("/-- The conjugated logarithm sum for `b = %d`, for a coefficient vector `c`. -/\n" % b)
    w("theorem conjlog_%d (c : Fin 13 → ℂ) :\n" % b)
    w("    ∑ j ∈ R0Exps, combC c (%d * j %% 120) * Complex.log (wJ j) =\n" % b)
    w("      (%s) * (Real.pi * I) := by\n" % rhs)
    w("  have h := sum_combC_comp c R0Exps (fun j => %d * j %% 120) (fun j => Complex.log (wJ j))\n"
      % b)
    w("  beta_reduce at h\n")
    lfs = ", ".join("lf_%d_%d" % (b, l) for l in range(1, 14))
    w("  rw [h, " + ", ".join("lf_%d_%d" % (b, l) for l in range(1, 8)) + ",\n    "
      + ", ".join("lf_%d_%d" % (b, l) for l in range(8, 14)) + "]\n")
    w("  push_cast\n  ring\n\n")
w("end PiFormula\n")
sys.stdout.buffer.write(out.getvalue().encode("utf-8"))
