# Generates the certificate parts of Theorem E (the optima):
#
#   python lean/scripts/egen.py classes > f1.lean   (section 1 of Classes.lean: the tables)
#   python lean/scripts/egen.py prime   > f2.lean   (section 2 of PrimeMeasure.lean)
#   python lean/scripts/egen.py terms   > f3.lean   (the certificate of FewestTerms.lean)
#
# "classes": the 119 conditions "rho(k) = 0" on the 8-dimensional space V fall into 35
# classes of proportional linear forms. The tables give, for each k < 120, the class of k,
# the integer vector of the class and the factor mu(k).
#
# "prime": the values of a combination at the positions on the four chains c, 2c, ..., 8c
# (c = 1, 7, 11, 17), and the linear facts used by the 13-node proof of mean(1/s) >= 7/24.
#
# "terms": a branch-and-bound tree proving that at least 40 of the 120 entries are non-zero,
# with a linear certificate for every derived fact. Lean checks it with a verified checker.
import io
import math
import os
import sys
from fractions import Fraction as Fr

import sympy as sp

sys.setrecursionlimit(100000)
HERE = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(HERE, "baileygen.py"), encoding="utf-8").read().split(
    "VAL = [1, 0, 1, 0, 0, 0, 0, 0]")[0]
G = {}
exec(compile(src, "baileygen_defs", "exec"), G)
N = 120
NAMES = ["namedA1", "namedA6", "namedA10", "namedL6", "namedL8", "namedL10", "namedL24",
         "namedTW"]
QV = [Fr(1), Fr(0), Fr(1), Fr(0), Fr(0), Fr(0), Fr(0), Fr(0)]


def row(k):
    return [Fr(int(x.p), int(x.q)) for x in G["row"](k)]


def primitive(v):
    den = 1
    for x in v:
        den = den * x.denominator // math.gcd(den, x.denominator)
    iv = [int(x * den) for x in v]
    g = 0
    for x in iv:
        g = math.gcd(g, abs(x))
    iv = [x // g for x in iv]
    if next(x for x in iv if x) < 0:
        iv = [-x for x in iv]
    return iv


# classes, in order of first appearance for k = 1, ..., 119
vecs, keyidx, cls, mu = [], {}, [35] * N, [Fr(0)] * N
for k in range(1, N):
    r = row(k)
    assert any(x != 0 for x in r)
    p = tuple(primitive(r))
    if p not in keyidx:
        keyidx[p] = len(vecs)
        vecs.append(list(p))
    cls[k] = keyidx[p]
    t = next(i for i in range(8) if p[i] != 0)
    mu[k] = r[t] / p[t]
    assert all(r[i] == mu[k] * p[i] for i in range(8))
assert all(x == 0 for x in row(0)) and all(x == 0 for x in row(120))
NC = len(vecs)
assert NC == 35
rep = [min(k for k in range(1, N) if cls[k] == i) for i in range(NC)]
UNITS = [c for c in range(N) if math.gcd(c, N) == 1]


def typerep(c):
    return {1: 1, 7: 7, 11: 11}.get(c % 12, 17)


def q(x):
    x = Fr(x)
    if x.denominator == 1:
        return "%d" % x.numerator if x.numerator >= 0 else "(%d)" % x.numerator
    return "(%d / %d)" % (x.numerator, x.denominator)


def wrap(prefix, body, indent, pat, width=100):
    import re
    text = prefix + (" " if prefix and not prefix.endswith("\n") else "") + body
    out_lines = []
    for raw in text.split("\n"):
        lead = raw[:len(raw) - len(raw.lstrip())]
        toks = [t for t in re.split(pat, raw.strip()) if t]
        cur = lead
        for t in toks:
            if len(cur.rstrip()) + len(t.rstrip()) > width - 1 and cur.strip():
                out_lines.append(cur.rstrip())
                cur = indent + t.lstrip()
            else:
                cur += t
        out_lines.append(cur.rstrip())
    return "\n".join(out_lines)


SUMS = r"(?= [+∧] )|(?= - )"
ITEMS = r"(?<=, )"
ROWS = r"(?<=\], )"


def solve_comb(target, hyps):
    """Coefficients c with target = sum c_i * hyps_i (exact), or None."""
    n = len(hyps)
    y = sp.symbols("y0:%d" % n)
    eqs = [sum(y[i] * sp.Rational(hyps[i][j].numerator, hyps[i][j].denominator)
               for i in range(n)) - sp.Rational(target[j].numerator, target[j].denominator)
           for j in range(8)]
    sol = sp.solve(eqs, y, dict=True)
    if not sol:
        return None
    zero = {u: 0 for u in y}          # free parameters (dependent hypotheses) are set to 0
    vals = [sp.Rational(sp.sympify(sol[0].get(v, 0)).subs(zero)) for v in y]
    assert all(sum(vals[i] * sp.Rational(hyps[i][j].numerator, hyps[i][j].denominator)
                   for i in range(n)) == sp.Rational(target[j].numerator, target[j].denominator)
               for j in range(8))
    return [Fr(int(v.p), int(v.q)) for v in vals]


# ------------------------------------------------------------------------------ classes
def gen_classes(w):
    w("/-! ## 1. The tables (generated by scripts/egen.py) -/\n\n")
    w("/-- The class of the condition `ρ(k) = 0`, for `k < 120`; 35 stands for `k = 0`. -/\n")
    w(wrap("def clsIdxTab : List ℕ :=\n ", "[" + ", ".join(str(x) for x in cls) + "]", "   ",
           ITEMS) + "\n\n")
    w("/-- The integer vector of each class: the linear form `∑ v_t q_t`. -/\n")
    w(wrap("def vecTab : List (List ℤ) :=\n ",
           "[" + ", ".join("[" + ", ".join(str(x) for x in v) + "]" for v in vecs) + "]",
           "   ", ROWS) + "\n\n")
    w("/-- The factor of `k`: the values of the eight named patterns at `k` are `mu k` times\n"
      "the vector of its class. -/\n")
    w(wrap("def muTab : List ℚ :=\n ", "[" + ", ".join(q(x).strip("()") if x.denominator == 1
                                                         and x >= 0 else q(x) for x in mu) + "]",
           "   ", ITEMS) + "\n\n")
    w("/-- The types of the 32 units modulo 120, in increasing order of the unit. -/\n")
    w(wrap("def unitTypes : List ℕ :=\n ", "[" + ", ".join(str(typerep(c)) for c in UNITS) + "]",
           "   ", ITEMS) + "\n\n")


# ------------------------------------------------------------------------------ prime
CHAINS = {a: [a * s for s in range(1, 9)] for a in (1, 7, 11, 17)}
BASE = [1, 7, 11, 17, 2, 34, 22, 14]
FACTS = [
    ("blk1", CHAINS[1], "V"), ("blk7", CHAINS[7], "V"), ("blk11", CHAINS[11], "V"),
    ("blk17", CHAINS[17], "V"),
    ("fc1", [7, 11, 17], 1),
    ("fc2", [1, 7, 11, 17, 2], 34),
    ("fc3", [1, 7, 11, 17, 34], 2),
    ("fc4", [1, 7, 11, 17, 2, 34, 14], 22),
    ("fc5", [1, 7, 11, 17, 2, 34, 22], 14),
    ("fe1", [33], 21), ("fe2", [21], 33),
    ("ff1", BASE + [3, 4], "V"),
    ("ff2", BASE + [51, 68], "V"),
    ("fg1", BASE + [21, 28], "V"),
    ("fg2", BASE + [33, 44], "V"),
    ("fg3", BASE + [21, 3], "V"),
    ("fg4", BASE + [21, 51], "V"),
]


def gen_prime(w):
    pos = sorted({k for ch in CHAINS.values() for k in ch} | {k for _, hs, t in FACTS for k in hs}
                 | {t for _, _, t in FACTS if t != "V"})
    w("/-! ## 2. Values on the four chains, and the linear facts (generated by "
      "scripts/egen.py) -/\n\n")
    for m in pos:
        r = row(m)
        ts = ["%s * q %d" % (q(c), i) for i, c in enumerate(r) if c != 0]
        w(wrap("theorem ncAt_%d (q : Fin 8 → ℚ) :\n    namedComb q %d =" % (m, m),
               (" + ".join(ts) if ts else "0") + " := by", "      ", SUMS) + "\n")
        parts = ["%s %d = %s" % (NAMES[i], m, q(r[i])) for i in range(8)]
        w(wrap("  have h :", " ∧ ".join(parts) + " := by", "     ", SUMS) + "\n    decide +kernel\n")
        w("  obtain ⟨h0, h1, h2, h3, h4, h5, h6, h7⟩ := h\n")
        w("  simp only [namedComb, h0, h1, h2, h3, h4, h5, h6, h7]\n  ring\n\n")
    for name, hyps, target in FACTS:
        tv = QV if target == "V" else row(target)
        cs = solve_comb(tv, [row(h) for h in hyps])
        assert cs is not None, name
        used = {h for c, h in zip(cs, hyps) if c != 0}
        args = " ".join("(%sh%d : namedComb q %d = 0)" % ("" if h in used else "_", h, h)
                        for h in hyps)
        concl = "q 0 + q 2 = 0" if target == "V" else "namedComb q %d = 0" % target
        w(wrap("theorem %s (q : Fin 8 → ℚ)" % name, args + " :\n    " + concl + " := by",
               "    ", r"(?<=\) )") + "\n")
        for h in hyps:
            if h in used:
                w("  rw [ncAt_%d] at h%d\n" % (h, h))
        if target != "V":
            w("  rw [ncAt_%d]\n" % target)
        ts = ["%s * h%d" % (q(c), h) for c, h in zip(cs, hyps) if c != 0]
        w(wrap("  linear_combination", " + ".join(ts) if ts else "0", "    ", SUMS) + "\n\n")


# ------------------------------------------------------------------------------ terms
FV = [[Fr(x) for x in v] for v in vecs]
SIZES = [sum(1 for k in range(1, N) if cls[k] == i) for i in range(NC)]


def reduce_vec(basis, v):
    v = list(v)
    for piv, r in basis:
        if v[piv] != 0:
            f = v[piv]
            v = [a - f * b for a, b in zip(v, r)]
    return v


def add_vec(basis, v):
    w = reduce_vec(basis, v)
    piv = next((i for i, x in enumerate(w) if x != 0), None)
    if piv is None:
        return basis
    w = [x / w[piv] for x in w]
    nb = []
    for p, r in basis:
        if r[piv] != 0:
            f = r[piv]
            r = tuple(a - f * b for a, b in zip(r, w))
        nb.append((p, r))
    nb.append((piv, tuple(w)))
    return tuple(nb)


def in_span(basis, v):
    return all(x == 0 for x in reduce_vec(basis, v))


_cache = {}


def closure(Z):
    key = frozenset(Z)
    if key not in _cache:
        basis = ()
        for i in sorted(key):
            basis = add_vec(basis, FV[i])
        cl = frozenset(i for i in range(NC) if in_span(basis, FV[i]))
        _cache[key] = _cache[cl] = (cl, basis, not in_span(basis, QV))
    return _cache[key]


def int_combination(target, idx):
    """Integers (d, c) with d * target = sum c_i * vecs[idx_i], d > 0. The vectors are
    linearly independent and the target lies in their span."""
    n = len(idx)
    A = [[FV[idx[j]][t] for j in range(n)] + [target[t]] for t in range(8)]
    piv, r = [], 0
    for col in range(n):
        p = next((i for i in range(r, 8) if A[i][col] != 0), None)
        assert p is not None
        A[r], A[p] = A[p], A[r]
        inv = 1 / A[r][col]
        A[r] = [x * inv for x in A[r]]
        for i in range(8):
            if i != r and A[i][col] != 0:
                f = A[i][col]
                A[i] = [a - f * b for a, b in zip(A[i], A[r])]
        piv.append(col)
        r += 1
    assert all(A[i][n] == 0 for i in range(r, 8))
    c = [A[i][n] for i in range(n)]
    d = 1
    for x in c:
        d = d * x.denominator // math.gcd(d, x.denominator)
    ci = [int(x * d) for x in c]
    assert all(d * target[t] == sum(ci[j] * FV[idx[j]][t] for j in range(n)) for t in range(8))
    return d, ci


def build(Zpath, Dpath, stats):
    cl, basis, feas = closure(Zpath)
    assert feas and not (cl & set(Dpath))
    known, order = set(Dpath), []
    changed = True
    while changed:
        changed = False
        for j in sorted(range(NC), key=lambda i: (-SIZES[i], i)):
            if j in cl or j in known:
                continue
            cl2, b2, feas2 = closure(set(cl) | {j})
            if not feas2:
                tgt = 35
            else:
                hit = sorted(cl2 & known)
                if not hit:
                    continue
                tgt = hit[0]
            order.append((j, tgt))
            known.add(j)
            changed = True
    free = [i for i in range(NC) if i not in cl and i not in known]
    ub = sum(SIZES[i] for i in cl) + sum(SIZES[i] for i in free)
    stats["nodes"] += 1
    if ub <= 79:
        total = sum(SIZES[i] for i in set(Dpath))
        node = ("done",)
        steps = []
        for j, tgt in order:
            if total >= 40:
                break
            tv = QV if tgt == 35 else FV[tgt]
            d, ci = int_combination(tv, list(Zpath) + [j])
            cs = [(z, c) for z, c in zip(list(Zpath) + [j], ci) if c != 0]
            steps.append((j, tgt, d, cs))
            total += SIZES[j]
        assert total >= 40
        for j, tgt, d, cs in reversed(steps):
            node = ("derive", j, tgt, d, cs, node)
        stats["derives"] += len(steps)
        return node
    i = min(free, key=lambda i: (-SIZES[i], i))
    return ("branch", i, build(Zpath + [i], Dpath, stats), build(Zpath, Dpath + [i], stats))


def size(node):
    if node[0] == "done":
        return 1
    if node[0] == "derive":
        return 1 + size(node[5])
    return 1 + size(node[2]) + size(node[3])


def gen_terms(w):
    stats = {"nodes": 0, "derives": 0}
    tree = build([], [], stats)
    defs = []
    counter = [0]

    def emit(node, lines, top):
        """Append the lines of the term for `node`; large subtrees become their own def."""
        if node[0] == "done":
            lines.append("Cert.done")
        elif node[0] == "derive":
            _, j, tgt, d, cs, rest = node
            body = "[" + ", ".join("(%d, %d)" % zc for zc in cs) + "]"
            lines.append("(Cert.derive %d %d %d %s" % (j, tgt, d, body))
            emit(rest, lines, False)
            lines[-1] += ")"
        else:
            _, i, t0, t1 = node
            if not top and size(node) > 25:
                counter[0] += 1
                name = "cert%d" % counter[0]
                sub = []
                emit(node, sub, True)
                defs.append((name, sub))
                lines.append(name)
                return
            lines.append("(Cert.branch %d" % i)
            emit(t0, lines, False)
            emit(t1, lines, False)
            lines[-1] += ")"

    top = []
    emit(tree, top, True)
    defs.append(("theCert", top))
    w("/-! ## 3. The certificate (generated by scripts/egen.py) -/\n\n")
    w("/-! %d nodes of the search tree and %d derived facts, in %d pieces. -/\n\n"
      % (stats["nodes"], stats["derives"], len(defs)))
    for name, lines in defs:
        if name == "theCert":
            w("/-- The certificate that at least 40 entries per period are non-zero. -/\n")
        w("def %s : Cert :=\n" % name)
        for ln in lines:
            w(wrap("  " + ln, "", "    ", ITEMS).rstrip() + "\n")
        w("\n")


out = io.StringIO()
mode = sys.argv[1]
if mode == "classes":
    gen_classes(out.write)
elif mode == "prime":
    gen_prime(out.write)
elif mode == "terms":
    gen_terms(out.write)
sys.stdout.buffer.write(out.getvalue().encode("utf-8"))
